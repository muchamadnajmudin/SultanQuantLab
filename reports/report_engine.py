def generate_all_reports(
    statistics: dict,
    trades,
    wfo_analysis: dict = None,
    monte_carlo_analysis: dict = None,
    risk_dashboard: dict = None,
):
    """
    Central report orchestrator.

    Generate:

    - TXT report
    - HTML report
    - Visual analytics
    - Trade journal

    """


    OUTPUT_DIR.mkdir(

        parents=True,

        exist_ok=True

    )



    results = {}



    # ---------------------------------------------
    # TEXT REPORT
    # ---------------------------------------------

    text_report = save_text_report(

        statistics

    )


    results["text_report"] = (

        text_report

    )



    # ---------------------------------------------
    # HTML REPORT
    # ---------------------------------------------

    html_report = generate_html_report(

        statistics=statistics,

        wfo_analysis=wfo_analysis,

        monte_carlo_analysis=monte_carlo_analysis,

        risk_dashboard=risk_dashboard,

    )


    results["html_report"] = (

        html_report

    )



    # ---------------------------------------------
    # VISUAL ANALYTICS
    # ---------------------------------------------

    visual_reports = generate_visual_reports(

        stats=statistics,

        trades=trades,

    )


    results["visual_reports"] = (

        visual_reports

    )



    # ---------------------------------------------
    # TRADE JOURNAL
    # ---------------------------------------------

    journal = save_trade_journal(

        trades

    )


    results["trade_journal"] = (

        journal

    )



    return results