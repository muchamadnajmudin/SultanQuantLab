# =====================================================
# CONFIG
# =====================================================

OUTPUT_DIR = Path(
    "reports/output"
)



TEXT_REPORT_FILE = (

    OUTPUT_DIR /

    "backtest_report.txt"

)



# =====================================================
# LEGACY TEXT REPORT
# =====================================================

def generate_report(
    statistics: dict
) -> str:
    """
    Generate backtest report text.

    Legacy function.
    """

    lines = []


    lines.append(
        "=" * 50
    )

    lines.append(
        "SULTAN QUANT OS BACKTEST REPORT"
    )

    lines.append(
        "=" * 50
    )


    lines.append(

        f"Generated : {datetime.now():%Y-%m-%d %H:%M:%S}"

    )


    lines.append("")



    for key, value in statistics.items():


        if key in [

            "equity_curve",

            "drawdown_curve"

        ]:

            continue



        if isinstance(value, float):

            value = round(

                value,

                2

            )



        lines.append(

            f"{key:20}: {value}"

        )



    lines.append("")



    lines.append(

        "=" * 50

    )



    lines.append(

        "Generated by Sultan Quant OS"

    )


    lines.append(

        "=" * 50

    )



    return "\n".join(
        lines
    )



# =====================================================
# SAVE TEXT REPORT
# =====================================================

def save_text_report(
    statistics: dict,
    filename=None,
):


    OUTPUT_DIR.mkdir(

        parents=True,

        exist_ok=True

    )


    report = generate_report(
        statistics
    )



    if filename:


        output = Path(
            filename
        )


    else:


        output = TEXT_REPORT_FILE



    output.write_text(

        report,

        encoding="utf-8"

    )


    return output

